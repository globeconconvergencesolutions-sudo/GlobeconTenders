function segmentsOf(name: string): string[] {
  const withoutParen = name.replace(/\([^)]*\)/g, " ");
  return withoutParen
    .split(/\s*(?:&|\/)\s*/)
    .map((part) => part.replace(/\s+/g, " ").trim().toLowerCase())
    .filter(Boolean);
}

function usablePhrase(phrase: string): boolean {
  if (phrase.length < 3) return false;
  const words = phrase.split(" ").filter(Boolean);
  if (words.length >= 2) return words.every((word) => word.length >= 2);
  if (phrase.length < 5) return false;
  return !SINGLE_BLOCK.has(phrase);
}

/** Phrases for a line that has no curated keyword list yet. */
export function phrasesForLine(name: string, slug: string): string[] {
  const found: string[] = [];
  const push = (value: string) => {
    const phrase = value.replace(/\s+/g, " ").trim().toLowerCase();
    if (!usablePhrase(phrase)) return;
    if (!found.includes(phrase)) found.push(phrase);
  };

  for (const extra of EXTRAS[slug] ?? []) push(extra);
  for (const segment of segmentsOf(name)) push(segment);
  return found.slice(0, 5);
}

export function keywordsForLine(line: {
  slug: string;
  name: string;
  keywords: string[];
}): string[] {
  if (line.keywords.length > 0) return line.keywords;
  return phrasesForLine(line.name, line.slug);
}
